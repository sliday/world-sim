export const nameSuffixes = [
  ...Array.from({ length: 256 }, (_, index) => `-${String(index + 1).padStart(3, "0")}`),
  ...wordSuffixes,
] as const;

export function identityHash32(value: string): number {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  hash ^= hash >>> 16;
  hash = Math.imul(hash, 0x7feb352d);
  hash ^= hash >>> 15;
  hash = Math.imul(hash, 0x846ca68b);
  return (hash ^ (hash >>> 16)) >>> 0;
}

function pick<T>(values: readonly T[], identity: string, namespace: string): T {
  return values[identityHash32(`${namespace}:${identity}`) % values.length]!;
}

export function generateAgentName(identity: string): string {
  const given = pick(givenNames, identity, "given");
  const surname = pick(surnames, identity, "surname");
  const suffix = pick(nameSuffixes, identity, "suffix");
  return `${given} ${surname}${suffix}`;
}

export const agentNameCatalog = {
  givenNames,
  surnames,
  suffixes: nameSuffixes,
} as const;
